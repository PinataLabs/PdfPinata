using System.Globalization;
using System.Text;

// Reads the Adobe Glyph List and Apple's standard glyph order and writes the tables
// PdfPinata.Fonts.GlyphNames looks glyph names and simple encodings up in. See README.md beside this file.

var input = Argument(args, "--in") ?? Path.Combine("tools", "GlyphNameTableGenerator");
var output = Argument(args, "--out") ?? Path.Combine("src", "PdfPinata", "Fonts");

Console.WriteLine($"in {input}, out {output}");
Directory.CreateDirectory(output);

// The glyph list: name;XXXX[ XXXX …]. A name that stands for several characters is a ligature or
// a presentation form, and no cmap has one entry for it, so only the single-character names are kept.
var glyphList = File.ReadAllLines(Path.Combine(input, "glyphlist.txt"))
    .Where(line => line.Length > 0 && line[0] != '#')
    .Select(line => line.Split(';'))
    .Where(fields => !fields[1].Contains(' '))
    .Select(fields => (Name: fields[0], CodePoint: int.Parse(fields[1], NumberStyles.HexNumber, CultureInfo.InvariantCulture)))
    .OrderBy(entry => entry.Name, StringComparer.Ordinal)
    .ToList();

if (glyphList.Select(entry => entry.Name).Distinct(StringComparer.Ordinal).Count() != glyphList.Count)
    throw new InvalidOperationException("The glyph list names a glyph twice.");
if (glyphList.Any(entry => entry.CodePoint > 0xFFFF))
    throw new InvalidOperationException("The glyph list names a character outside the basic multilingual plane, which the table cannot hold.");

var macStandardNames = File.ReadAllLines(Path.Combine(input, "mac-standard-names.txt"))
    .Where(line => line.Length > 0)
    .ToList();
if (macStandardNames.Count != 258)
    throw new InvalidOperationException($"Apple's standard glyph order has 258 names, not {macStandardNames.Count}.");

Encoding.RegisterProvider(CodePagesEncodingProvider.Instance);

// WinAnsiEncoding is code page 1252 as ISO 32000-1 Annex D gives it: 0xA0 is the glyph space and
// 0xAD the glyph hyphen, and every code above 0x20 that the code page leaves undefined is bullet.
var winAnsi = new ushort[256];
var cp1252 = Encoding.GetEncoding(1252, EncoderFallback.ExceptionFallback, DecoderFallback.ReplacementFallback);
for (var code = 0x20; code < 256; code++)
{
    var character = cp1252.GetString([(byte)code])[0];
    winAnsi[code] = code switch
    {
        0x7F or 0x81 or 0x8D or 0x8F or 0x90 or 0x9D => 0x2022,
        0xA0 => 0x0020,
        0xAD => 0x002D,
        _ => character
    };
}

// MacRomanEncoding is the Mac OS Roman code page as ISO 32000-1 Annex D gives it: 0xCA is the glyph
// space, and 0xDB is currency where Mac OS 8.5 and later put the euro.
var macRoman = new ushort[256];
var cp10000 = Encoding.GetEncoding(10000, EncoderFallback.ExceptionFallback, DecoderFallback.ReplacementFallback);
for (var code = 0x20; code < 256; code++)
{
    if (code == 0x7F)
        continue;
    macRoman[code] = code switch
    {
        0xCA => 0x0020,
        0xDB => 0x00A4,
        _ => cp10000.GetString([(byte)code])[0]
    };
}

var text = new StringBuilder();
text.AppendLine("// <auto-generated>");
text.AppendLine("//   Generated by tools/GlyphNameTableGenerator. Do not edit by hand. Regenerate with:");
text.AppendLine("//     dotnet run --project tools/GlyphNameTableGenerator");
text.AppendLine("//");
text.AppendLine("//   The glyph names and the characters they stand for are the Adobe Glyph List 2.0,");
text.AppendLine("//   Copyright 2002-2019 Adobe (http://www.adobe.com/), redistributed under the licence in");
text.AppendLine("//   tools/GlyphNameTableGenerator/glyphlist-LICENSE.md.");
text.AppendLine("// </auto-generated>");
text.AppendLine();
text.AppendLine("namespace PdfPinata.Fonts;");
text.AppendLine();
text.AppendLine("/// <summary>The tables behind <see cref=\"GlyphNames\"/>. Use that class.</summary>");
text.AppendLine("static partial class GlyphNameTables");
text.AppendLine("{");

text.AppendLine("    /// <summary>The glyph list's names, sorted ordinally and run together; <see cref=\"GlyphListNameStarts\"/> says where each begins.</summary>");
text.AppendLine("    internal const string GlyphListNames =");
var joined = string.Concat(glyphList.Select(entry => entry.Name));
WriteStringChunks(text, joined);

text.AppendLine("    /// <summary>Where each name begins in <see cref=\"GlyphListNames\"/>, with the end of the last one after them.</summary>");
var starts = new List<int>();
var at = 0;
foreach (var entry in glyphList)
{
    starts.Add(at);
    at += entry.Name.Length;
}
starts.Add(at);
var startType = at > ushort.MaxValue ? "int" : "ushort";
text.AppendLine($"    internal static readonly {startType}[] GlyphListNameStarts =");
WriteNumbers(text, starts);

text.AppendLine("    /// <summary>The character each name stands for, in the order of the names.</summary>");
text.AppendLine("    internal static readonly ushort[] GlyphListCharacters =");
WriteNumbers(text, glyphList.Select(entry => entry.CodePoint), hex: true);

text.AppendLine("    /// <summary>The names of Apple's 258 standard glyphs, which a <c>post</c> table numbers rather than spells.</summary>");
text.AppendLine("    internal static readonly string[] MacStandardNames =");
text.AppendLine("    {");
for (var i = 0; i < macStandardNames.Count; i += 8)
    text.AppendLine("        " + string.Join(" ", macStandardNames.Skip(i).Take(8).Select(name => $"\"{name}\",")));
text.AppendLine("    };");
text.AppendLine();

text.AppendLine("    /// <summary>The character each code of WinAnsiEncoding stands for, 0 where it stands for none.</summary>");
text.AppendLine("    internal static readonly ushort[] WinAnsiCharacters =");
WriteNumbers(text, winAnsi.Select(c => (int)c), hex: true);

text.AppendLine("    /// <summary>The character each code of MacRomanEncoding stands for, 0 where it stands for none.</summary>");
text.AppendLine("    internal static readonly ushort[] MacRomanCharacters =");
WriteNumbers(text, macRoman.Select(c => (int)c), hex: true);

text.AppendLine("}");

var path = Path.Combine(output, "GlyphNameTables.g.cs");
File.WriteAllText(path, text.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"wrote {path}: {glyphList.Count} glyph names");

static void WriteStringChunks(StringBuilder text, string value)
{
    const int width = 90;
    for (var i = 0; i < value.Length; i += width)
    {
        var chunk = value.Substring(i, Math.Min(width, value.Length - i));
        var last = i + width >= value.Length;
        text.AppendLine($"        \"{chunk}\"{(last ? ";" : " +")}");
    }
    text.AppendLine();
}

static void WriteNumbers(StringBuilder text, IEnumerable<int> numbers, bool hex = false)
{
    var list = numbers.ToList();
    text.AppendLine("    {");
    const int perLine = 16;
    for (var i = 0; i < list.Count; i += perLine)
    {
        var line = list.Skip(i).Take(perLine)
            .Select(n => hex ? $"0x{n:X4}," : n.ToString(CultureInfo.InvariantCulture) + ",");
        text.AppendLine("        " + string.Join(" ", line));
    }
    text.AppendLine("    };");
    text.AppendLine();
}

static string Argument(string[] args, string name)
{
    var index = Array.IndexOf(args, name);
    return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
}
