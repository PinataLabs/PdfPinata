using System.Globalization;
using System.Text;

// Reads Adobe's Core14 AFM files and writes the width and encoding tables PdfPinata.Fonts looks the
// standard 14 fonts up in. See README.md beside this file.

var afmDirectory = Argument(args, "--afm") ?? Path.Combine("tools", "Core14MetricsGenerator", "afm");
var output = Argument(args, "--out") ?? Path.Combine("src", "PdfPinata", "Fonts");

Console.WriteLine($"afm {afmDirectory}, out {output}");
Directory.CreateDirectory(output);

// Ordinal order of the PostScript names. It is the order of the enum the generator writes, and the
// order the tables are indexed in, so reading the files in any other order changes nothing.
var fonts = Directory.GetFiles(afmDirectory, "*.afm")
    .Select(ReadAfm)
    .OrderBy(f => f.Name, StringComparer.Ordinal)
    .ToList();

if (fonts.Count != 14)
    throw new InvalidOperationException($"Expected the 14 Core14 AFM files in {afmDirectory}, found {fonts.Count}.");

// Three glyph name sets, one per character set: the twelve text fonts share one, and Symbol and
// ZapfDingbats each have their own. A pool is the sorted, distinct names of its fonts.
const int Latin = 0, Symbol = 1, Zapf = 2;
int PoolOf(AfmFont f) => f.Name == "Symbol" ? Symbol : f.Name == "ZapfDingbats" ? Zapf : Latin;

var poolNames = new List<string>[3];
for (var p = 0; p < 3; p++)
{
    poolNames[p] = fonts.Where(f => PoolOf(f) == p)
        .SelectMany(f => f.Glyphs.Select(g => g.Name))
        .Distinct(StringComparer.Ordinal)
        .OrderBy(n => n, StringComparer.Ordinal)
        .ToList();
}

var poolIndex = poolNames
    .Select(names => names.Select((n, i) => (n, i)).ToDictionary(t => t.n, t => t.i, StringComparer.Ordinal))
    .ToArray();

const ushort Absent = ushort.MaxValue;

// A font's widths, indexed by its pool's glyph numbers. Absent glyphs are 0xFFFF, because 0 is a
// width a glyph may legitimately have.
ushort[] WidthsOf(AfmFont f)
{
    var pool = PoolOf(f);
    var widths = new ushort[poolNames[pool].Count];
    Array.Fill(widths, Absent);
    foreach (var g in f.Glyphs)
        widths[poolIndex[pool][g.Name]] = checked((ushort)g.Width);
    return widths;
}

// A font's built-in encoding: for each code, the pool index of the glyph it names, or 0xFFFF.
ushort[] EncodingOf(AfmFont f)
{
    var pool = PoolOf(f);
    var encoding = new ushort[256];
    Array.Fill(encoding, Absent);
    foreach (var g in f.Glyphs.Where(g => g.Code >= 0))
        encoding[g.Code] = checked((ushort)poolIndex[pool][g.Name]);
    return encoding;
}

var widthsByFont = fonts.Select(WidthsOf).ToList();
var encodingsByFont = fonts.Select(EncodingOf).ToList();

// The twelve text fonts say StandardEncoding in their AFMs, so their code columns must agree. One
// table is written for them, and only after that is checked rather than assumed.
var latinEncodings = fonts.Select((f, i) => (f, i)).Where(t => PoolOf(t.f) == Latin).ToList();
foreach (var (f, i) in latinEncodings)
{
    if (!encodingsByFont[i].SequenceEqual(encodingsByFont[latinEncodings[0].i]))
        throw new InvalidOperationException($"{f.Name} does not have the same built-in encoding as {latinEncodings[0].f.Name}.");
}

// Fonts whose arrays are identical share one array: the four Courier faces, an upright face and its
// slanted twin in Helvetica. Each distinct array is named for the first font that has it.
var sb = new StringBuilder();
sb.Append("// <auto-generated>\n");
sb.Append("//   Generated from Adobe's Core14 AFM files by tools/Core14MetricsGenerator.\n");
sb.Append("//   Do not edit by hand. Regenerate with:\n");
sb.Append("//     dotnet run --project tools/Core14MetricsGenerator\n");
sb.Append("//\n");
sb.Append("//   Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems Incorporated. All Rights Reserved.\n");
sb.Append("//   The advance widths and encodings below are taken from the 14 PostScript AFM files that\n");
sb.Append("//   Adobe distributes with the notice kept beside them in tools/Core14MetricsGenerator/afm/MustRead.html,\n");
sb.Append("//   which permits them to be used, copied and distributed for any purpose and without charge\n");
sb.Append("//   provided that all copyright notices are retained.\n");
sb.Append("// </auto-generated>\n\n");
sb.Append("namespace PdfPinata.Fonts;\n\n");

sb.Append("/// <summary>One of the standard 14 fonts, in the order the tables in <see cref=\"Core14Tables\"/> are indexed.</summary>\n");
sb.Append("internal enum Core14Font : byte\n{\n");
foreach (var f in fonts)
    sb.Append($"    {f.Name.Replace("-", "")},\n");
sb.Append("}\n\n");

sb.Append("/// <summary>The width and encoding tables of the standard 14 fonts. Use <see cref=\"Core14Metrics\"/>.</summary>\n");
sb.Append("static partial class Core14Tables\n{\n");

sb.Append("    /// <summary>The PostScript name of each font, indexed by <see cref=\"Core14Font\"/>.</summary>\n");
sb.Append("    internal static readonly string[] PostScriptNames =\n    {\n");
sb.Append(Wrap(fonts.Select(f => Quote(f.Name))));
sb.Append("    };\n\n");

sb.Append("    /// <summary>The glyph name pool each font draws from: 0 for the text fonts, 1 for Symbol, 2 for ZapfDingbats.</summary>\n");
sb.Append("    internal static readonly byte[] PoolOfFont =\n    {\n");
sb.Append(Wrap(fonts.Select(f => PoolOf(f).ToString(CultureInfo.InvariantCulture))));
sb.Append("    };\n\n");

string[] poolLabels = { "text fonts", "Symbol", "ZapfDingbats" };
string[] poolNamesFor = { "Latin", "Symbol", "ZapfDingbats" };
for (var p = 0; p < 3; p++)
{
    var names = poolNames[p];
    sb.Append($"    /// <summary>The glyph names of the {poolLabels[p]}, sorted ordinally and run together; <see cref=\"{poolNamesFor[p]}NameStarts\"/> says where each begins.</summary>\n");
    sb.Append($"    internal const string {poolNamesFor[p]}Names =\n");
    foreach (var chunk in Chunks(string.Concat(names), 90))
        sb.Append($"        \"{chunk}\" +\n");
    sb.Length -= 3;
    sb.Append(";\n\n");

    var starts = new List<int>();
    var at = 0;
    foreach (var n in names)
    {
        starts.Add(at);
        at += n.Length;
    }
    starts.Add(at);
    sb.Append($"    /// <summary>Where each of the {names.Count} names in <see cref=\"{poolNamesFor[p]}Names\"/> begins, and, last, where it ends.</summary>\n");
    sb.Append($"    internal static readonly ushort[] {poolNamesFor[p]}NameStarts =\n    {{\n");
    sb.Append(Wrap(starts.Select(s => s.ToString(CultureInfo.InvariantCulture))));
    sb.Append("    };\n\n");
}

sb.Append("    // Each array below is a glyph number to advance width, in thousandths of an em, 0xFFFF where the font has no such glyph.\n");
var widthNames = new string[fonts.Count];
var seenWidths = new List<(ushort[] Data, string Name)>();
for (var i = 0; i < fonts.Count; i++)
{
    var existing = seenWidths.FirstOrDefault(s => s.Data.SequenceEqual(widthsByFont[i]));
    if (existing.Name != null)
    {
        widthNames[i] = existing.Name;
        continue;
    }

    var name = "Widths" + fonts[i].Name.Replace("-", "");
    widthNames[i] = name;
    seenWidths.Add((widthsByFont[i], name));
    sb.Append($"    static readonly ushort[] {name} =\n    {{\n");
    sb.Append(Wrap(widthsByFont[i].Select(w => w.ToString(CultureInfo.InvariantCulture))));
    sb.Append("    };\n\n");
}

sb.Append("    /// <summary>The advance widths of each font, indexed by <see cref=\"Core14Font\"/>.</summary>\n");
sb.Append("    internal static readonly ushort[][] Widths =\n    {\n");
sb.Append(Wrap(widthNames));
sb.Append("    };\n\n");

sb.Append("    // Each array below is a character code to glyph number, 0xFFFF where the code names nothing.\n");
sb.Append("    static readonly ushort[] StandardEncoding =\n    {\n");
sb.Append(Wrap(encodingsByFont[latinEncodings[0].i].Select(e => e.ToString(CultureInfo.InvariantCulture))));
sb.Append("    };\n\n");
foreach (var special in new[] { "Symbol", "ZapfDingbats" })
{
    var i = fonts.FindIndex(f => f.Name == special);
    sb.Append($"    static readonly ushort[] {special}Encoding =\n    {{\n");
    sb.Append(Wrap(encodingsByFont[i].Select(e => e.ToString(CultureInfo.InvariantCulture))));
    sb.Append("    };\n\n");
}

sb.Append("    /// <summary>The built-in encoding of each font, indexed by <see cref=\"Core14Font\"/>. The text fonts share StandardEncoding.</summary>\n");
sb.Append("    internal static readonly ushort[][] Encodings =\n    {\n");
sb.Append(Wrap(fonts.Select(f => f.Name is "Symbol" or "ZapfDingbats" ? f.Name + "Encoding" : "StandardEncoding")));
sb.Append("    };\n}\n");

Write(Path.Combine(output, "Core14Tables.g.cs"), sb.ToString());

static string Quote(string s) => "\"" + s + "\"";

static IEnumerable<string> Chunks(string s, int size)
{
    for (var i = 0; i < s.Length; i += size)
        yield return s.Substring(i, Math.Min(size, s.Length - i));
}

static AfmFont ReadAfm(string path)
{
    string name = null;
    var glyphs = new List<AfmGlyph>();
    foreach (var raw in File.ReadLines(path))
    {
        var line = raw.Trim();
        if (line.StartsWith("FontName ", StringComparison.Ordinal))
            name = line.Substring("FontName ".Length).Trim();
        else if (line.StartsWith("C ", StringComparison.Ordinal) || line.StartsWith("CH ", StringComparison.Ordinal))
        {
            var code = -1;
            var width = -1;
            string glyph = null;
            foreach (var field in line.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                var parts = field.Split(' ', 2, StringSplitOptions.TrimEntries);
                switch (parts[0])
                {
                    case "C": code = int.Parse(parts[1], CultureInfo.InvariantCulture); break;
                    case "WX": width = (int)double.Parse(parts[1], CultureInfo.InvariantCulture); break;
                    case "N": glyph = parts[1]; break;
                }
            }

            if (glyph == null || width < 0)
                throw new InvalidOperationException($"{path}: cannot read '{line}'.");
            glyphs.Add(new AfmGlyph(code, width, glyph));
        }
    }

    if (name == null)
        throw new InvalidOperationException($"{path} has no FontName.");
    return new AfmFont(name, glyphs);
}

static string Argument(string[] args, string name)
{
    var i = Array.IndexOf(args, name);
    return i >= 0 && i + 1 < args.Length ? args[i + 1] : null;
}

static string Wrap(IEnumerable<string> items)
{
    var sb = new StringBuilder();
    var line = new StringBuilder("        ");
    foreach (var item in items)
    {
        if (line.Length + item.Length + 2 > 100)
        {
            sb.Append(line.ToString().TrimEnd()).Append('\n');
            line = new StringBuilder("        ");
        }
        line.Append(item).Append(", ");
    }

    if (line.ToString().Trim().Length > 0)
        sb.Append(line.ToString().TrimEnd()).Append('\n');

    return sb.ToString();
}

static void Write(string path, string text)
{
    // Normalised on the way out, as UnicodeTableGenerator does, so regenerating on a machine with
    // other line endings is no diff of the whole file.
    text = text.Replace("\r\n", "\n").Replace("\n", Environment.NewLine);

    File.WriteAllText(path, text, new UTF8Encoding(false));
    Console.WriteLine($"wrote {path} ({new FileInfo(path).Length} bytes)");
}

record AfmGlyph(int Code, int Width, string Name);

record AfmFont(string Name, List<AfmGlyph> Glyphs);
